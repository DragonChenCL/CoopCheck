assert.equal(new Set([...sitemap.matchAll(/<loc>(.*?)<\/loc>/g)].map(x=>x[1])).size,124);
const headings=new Set(),descs=new Set(),titles=new Set();
for(const p of pages){
 const html=read("site/guides/"+p.slug+".html");
 assert.equal(html,p.html,"generated intent pages must be synced "+p.slug);
 const meta=html.match(/<meta name="description" content="([^"]+)"/)?.[1];
 const title=html.match(/<title>([^<]+)<\/title>/)?.[1];
 const h1=html.match(/<h1>([^<]+)<\/h1>/)?.[1];
 assert(meta&&title&&h1,"SEO metadata + visible H1");
 assert(meta.length<=165&&title.length<=90,"metadata length");
 titles.add(title);descs.add(meta);headings.add(h1);
 const url="https://coopcheck.serunio.com/guides/"+p.slug+".html";
 assert(html.includes('rel="canonical" href="'+url+'"'),"indexable self-canonical "+p.slug);
 assert(html.includes('<meta name="robots" content="index,follow">'));
 assert(sitemap.includes("<loc>"+url+"</loc>"),"unique sitemap entry "+p.slug);
 assert(html.includes("application/ld+json"),"structured data "+p.slug);
 assert(html.includes("Oregon State University Extension")&&html.includes("Penn State Extension"),"source-backed guide "+p.slug);
 assert(html.includes("not")&&html.includes("municipal"),"no legal clearance claims "+p.slug);
 assert(html.includes("/guides/chicken-coop-size-calculator.html"),"connected sizing hub "+p.slug);
 assert(html.includes("coop-plan.html")||html.includes("coop-plan.html".replace(".html",".html")),"plan reference "+p.slug);
 assert(html.length>6200,"not a thin doorway "+p.slug);
 if(p.slug!=="free-chicken-coop-floor-plans"){
  assert(html.includes('data-coop-tool='),"functional tool, not an inert label "+p.slug);
  for(const marker of ["toolStatus","toolOutput","toolChart"])assert(html.includes('id="'+marker+'"'),"UI output hook "+marker);
 }else{
  assert(!html.includes('data-coop-tool='),"free floor plans are concept directory, not fake paid CAD");
  assert(html.includes("engineering")&&html.includes("Save PDF"),"explicit construction caveats");
 }
}
